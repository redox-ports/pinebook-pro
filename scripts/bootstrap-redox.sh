#!/usr/bin/env bash
# Prepare a local Redox build tree for the Pinebook Pro port.
#
# Clones the upstream Redox repository (GitHub mirror), injects our filesystem
# config overlay and writes the build .config. Upstream is never forked: the
# overlay lives in this repository and is copied into the clone. The build
# tree defaults to build/redox inside this repository (gitignored).
#
# Usage:
#   scripts/bootstrap-redox.sh [--podman|--native] [--dir DIR] [--repo-binary]
#
# Modes:
#   --podman  PODMAN_BUILD=1, containerized build (default; the "always
#             works" path). The host still needs rustup/cargo: the installer
#             tools (fstools) are built outside the container.
#   --native  PODMAN_BUILD=0, build with the host toolchain. Runs the
#             upstream native_bootstrap.sh (distro packages via sudo,
#             rustup, just, cbindgen).
#
# Environment overrides:
#   PBP_REDOX_DIR     build tree location (default: <repo>/build/redox)
#   PBP_REPO_BINARY   1 to record REPO_BINARY?=1 in .config (prebuilt
#                     aarch64 packages; availability unverified, README risk 7)

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Tools installed into ~/.cargo/bin must be visible even when this script
# installs rustup earlier in the same run (the rustup env file is sourced
# only inside the child process).
export PATH="$HOME/.cargo/bin:$PATH"
OVERLAY_SRC="$REPO_ROOT/config/aarch64/pinebook-pro/minimal.toml"
REDOX_URL="https://github.com/redox-os/redox.git"
REDOX_DIR="${PBP_REDOX_DIR:-$REPO_ROOT/build/redox}"
MODE="podman"
REPO_BINARY="${PBP_REPO_BINARY:-0}"

die() {
    echo "error: $*" >&2
    exit 1
}

usage() {
    echo "usage: scripts/bootstrap-redox.sh [--podman|--native] [--dir DIR] [--repo-binary]"
    exit 0
}

while [ $# -gt 0 ]; do
    case "$1" in
        --podman) MODE="podman" ;;
        --native) MODE="native" ;;
        --dir) REDOX_DIR="${2:?--dir needs a value}"; shift ;;
        --repo-binary) REPO_BINARY=1 ;;
        -h|--help) usage ;;
        *) die "unknown argument: $1 (see --help)" ;;
    esac
    shift
done

command -v git >/dev/null 2>&1 || die "git is required"
command -v make >/dev/null 2>&1 || die "make is required"
[ -f "$OVERLAY_SRC" ] || die "overlay config missing: $OVERLAY_SRC"

if [ "$MODE" = "podman" ]; then
    command -v podman >/dev/null 2>&1 || die "podman not found: install podman, or run with --native"
fi

# Clone or update the upstream tree (never fork it).
if [ -d "$REDOX_DIR/.git" ]; then
    echo "==> updating existing clone in $REDOX_DIR"
    git -C "$REDOX_DIR" pull --ff-only \
        || echo "warning: fast-forward pull failed; keeping the local state" >&2
else
    echo "==> cloning upstream Redox into $REDOX_DIR"
    git clone "$REDOX_URL" "$REDOX_DIR"
fi

# Build settings. "?=" keeps environment variables authoritative.
PODMAN_VALUE=0
[ "$MODE" = "podman" ] && PODMAN_VALUE=1
cat > "$REDOX_DIR/.config" <<EOF
# Generated by pinebook-pro scripts/bootstrap-redox.sh. Local file, never commit.
ARCH?=aarch64
CONFIG_NAME?=minimal
FILESYSTEM_CONFIG?=config/aarch64/pinebook-pro/minimal.toml
PODMAN_BUILD?=$PODMAN_VALUE
REPO_BINARY?=$REPO_BINARY
EOF

# Inject our board config overlay (idempotent).
mkdir -p "$REDOX_DIR/config/aarch64/pinebook-pro"
cp -f "$OVERLAY_SRC" "$REDOX_DIR/config/aarch64/pinebook-pro/minimal.toml"

if [ "$MODE" = "native" ]; then
    echo "==> installing native build dependencies via upstream native_bootstrap.sh (uses sudo)"
    # Upstream ends with an optional emulator block (qemu-kvm and friends).
    # On some Ubuntu releases qemu-kvm is a virtual package with no
    # installation candidate, which aborts the script. The essential
    # packages and rustup are installed before that block, so a failure
    # there is non-fatal for us; required tools are verified below.
    if bash "$REDOX_DIR/native_bootstrap.sh" -d -y; then
        echo "==> upstream dependency install finished"
    else
        echo "warning: native_bootstrap.sh failed (commonly on the optional QEMU packages);" >&2
        echo "         continuing: required tools are verified below" >&2
    fi
fi

# fstools (redox-installer, redoxfs) is always built with the host cargo,
# even in podman mode (FSTOOLS_IN_PODMAN=0 upstream default).
command -v cargo >/dev/null 2>&1 \
    || die "host rustup/cargo not found (required even in podman mode): https://rustup.rs"

if [ "$MODE" = "native" ]; then
    if ! command -v just >/dev/null 2>&1 || ! command -v cbindgen >/dev/null 2>&1; then
        echo "==> installing just and cbindgen via cargo (versions pinned to match upstream)"
        cargo install just@1.50.0
        cargo install cbindgen@0.29.0
    fi
    MISSING=""
    for tool in rustup just cbindgen nasm; do
        command -v "$tool" >/dev/null 2>&1 || MISSING="$MISSING $tool"
    done
    [ -z "$MISSING" ] || die "missing required tools:$MISSING - install them and rerun"
fi

echo
echo "Redox tree ready: $REDOX_DIR"
echo "Next: scripts/build-image.sh"
echo "      (the first build downloads and compiles a lot; expect a long run)"
